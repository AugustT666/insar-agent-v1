"""Unit tests for the central output resolver (Phase 1)."""
from __future__ import annotations

import pytest

from insar_agent.core.layout import RunLayout
from insar_agent.core.output_resolver import (
    OutputEscapeError,
    enforce_inside_run,
    resolve_output,
)
from insar_agent.core.project import new_project


@pytest.fixture
def workspace(tmp_path):
    ws = tmp_path / "workspace"
    ws.mkdir()
    return ws


def test_default_builds_run_root_with_subdir(workspace):
    res = resolve_output(
        workspace_root=str(workspace),
        task_id="d-insar-isce2",
        run_id="r1",
        subdir="dem",
    )
    assert res.run_root == workspace / "d-insar-isce2" / "outputs" / "r1"
    assert res.target == res.run_root / "dem"
    assert res.override is False
    assert res.target.exists()  # created by default


def test_default_empty_subdir_is_run_root(workspace):
    res = resolve_output(workspace_root=str(workspace), task_id="d-insar-isce2", run_id="r1")
    assert res.target == res.run_root


def test_run_id_autogenerated_when_absent(workspace):
    res = resolve_output(workspace_root=str(workspace), task_id="d-insar-isce2")
    assert res.layout.run_id.startswith("d-insar-isce2_")
    assert res.run_root.parent.name == "outputs"


def test_override_inside_run_root_is_accepted(workspace):
    run_root = workspace / "d-insar-isce2" / "outputs" / "r1"
    custom = run_root / "my_products"
    res = resolve_output(
        workspace_root=str(workspace),
        task_id="d-insar-isce2",
        run_id="r1",
        output_dir=str(custom),
    )
    assert res.override is True
    assert res.target.resolve() == custom.resolve()
    assert res.run_root == run_root


def test_override_outside_run_root_raises(workspace, tmp_path):
    outside = tmp_path / "elsewhere"
    with pytest.raises(OutputEscapeError):
        resolve_output(
            workspace_root=str(workspace),
            task_id="d-insar-isce2",
            run_id="r1",
            output_dir=str(outside),
        )


def test_override_pointing_at_existing_run_dir_adopts_that_run(workspace):
    # output_dir points inside an existing run tree → that run_id is adopted,
    # even though no run_id kwarg was passed.
    existing = workspace / "d-insar-isce2" / "outputs" / "older_run" / "stack"
    res = resolve_output(output_dir=str(existing))
    assert res.override is True
    assert res.run_root.name == "older_run"
    assert res.target.resolve() == existing.resolve()


def test_strict_disabled_allows_escape(workspace, tmp_path, monkeypatch):
    monkeypatch.setenv("INSAR_STRICT_OUTPUT", "0")
    outside = tmp_path / "elsewhere"
    res = resolve_output(
        workspace_root=str(workspace),
        task_id="d-insar-isce2",
        run_id="r1",
        output_dir=str(outside),
        create=False,
    )
    assert res.override is True
    assert res.target.resolve() == outside.resolve()


def test_project_recovers_existing_run_root(workspace):
    proj = new_project(
        name="d-insar-isce2",
        engine="isce2",
        workflow="d-insar",
        workspace_root=str(workspace),
        task_id="d-insar-isce2",
    )
    run_root = workspace / "d-insar-isce2" / "outputs" / "r99"
    proj.runconfig = {
        "runconfig": {
            "groups": {
                "product_path_group": {"product_path": str(run_root / "products")}
            }
        }
    }
    res = resolve_output(project=proj, subdir="mintpy")
    assert res.run_root == run_root
    assert res.target == run_root / "mintpy"


def test_resolve_run_layout_prefers_pinned_run_id(workspace):
    from insar_agent.core.project import Project
    from insar_agent.core.output_resolver import resolve_run_layout

    proj = Project(
        name="t",
        engine="isce3",
        workflow="insar",
        workspace_root=str(workspace),
        task_id="d-insar-isce3",
        run_id="d-insar-isce3_PINNED",
    )
    layout = resolve_run_layout(proj)
    assert layout is not None and layout.run_id == "d-insar-isce3_PINNED"


def test_enforce_inside_run_returns_path_when_contained(workspace):
    layout = RunLayout(workspace_root=str(workspace), task_id="t", run_id="r1")
    child = layout.run_root / "products" / "x.h5"
    assert enforce_inside_run(child, layout) == child


def test_enforce_inside_run_raises_when_outside(workspace, tmp_path):
    layout = RunLayout(workspace_root=str(workspace), task_id="t", run_id="r1")
    with pytest.raises(OutputEscapeError):
        enforce_inside_run(tmp_path / "nope", layout)


def test_resolve_child_blocks_traversal(workspace):
    layout = RunLayout(workspace_root=str(workspace), task_id="t", run_id="r1")
    with pytest.raises(ValueError):
        layout.resolve_child("..", "..", "escape")


def test_run_logs_dir_under_run_root(workspace):
    from insar_agent.core.output_resolver import run_logs_dir
    p = run_logs_dir(workspace_root=str(workspace), task_id="d-insar-isce2", run_id="r1")
    assert p == workspace / "d-insar-isce2" / "outputs" / "r1" / "logs"


def test_param_advice_output_dir_prefers_pinned_run(workspace):
    """param-advisor output must join the project's pinned run (one run per task),
    even for ISCE2 which has no product_path_group to recover the run from."""
    from insar_agent.core.project import Project
    from insar_agent.core.output_resolver import param_advice_output_dir
    proj = Project(
        name="t", engine="isce2", workflow="topsapp",
        workspace_root=str(workspace), task_id="d-insar-isce2",
        run_id="d-insar-isce2_PINNED",
    )
    p = param_advice_output_dir(proj, output_dir="", task_id="d-insar-isce2")
    assert p == workspace / "d-insar-isce2" / "outputs" / "d-insar-isce2_PINNED" / "param_advisor"


def test_resolve_output_reuses_project_pinned_run(workspace):
    """A product prepare tool (no run_id, no override) must reuse the project's
    pinned run via resolve_output, so prepare_stack/network join the one run."""
    import json
    task = "stack-insar-isce2"
    pdir = workspace / task / ".insar_agent"
    pdir.mkdir(parents=True)
    (pdir / "project.json").write_text(json.dumps({
        "name": "t", "engine": "isce2", "workflow": "stack",
        "workspace_root": str(workspace), "task_id": task,
        "run_id": "stack-insar-isce2_PINNED",
    }), encoding="utf-8")
    res = resolve_output(workspace_root=str(workspace), task_id=task, subdir="stack")
    assert res.layout.run_id == "stack-insar-isce2_PINNED"
    assert res.target == workspace / task / "outputs" / "stack-insar-isce2_PINNED" / "stack"
